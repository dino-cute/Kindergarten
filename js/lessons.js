const cap = w => w.charAt(0).toUpperCase() + w.slice(1);
export const sentence = (w, art) => `It's ${art ? art + ' ' : ''}${w}.`;
export const findLine = w => `Where is the ${w}?`;
export const sayOf = (L, wd) => L.say ? L.say(wd) : sentence(wd[0], wd[2]);
export const findOf = (L, w) => L.find ? L.find(w, L.words.find(x => x[0] === w)) : findLine(w);

